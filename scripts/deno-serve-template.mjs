export const serverServeSource = [
    'import { handle } from "./entry.mjs";',
    'import { createDenoAstroRenderOptions, isDenoWebSocketUpgradeRequest } from "./deno-websocket.mjs";',
    "",
    'const clientRootUrl = new URL("../client/", import.meta.url);',
    "",
    "const contentTypeByExtension = {",
    '    ".css": "text/css; charset=utf-8",',
    '    ".gif": "image/gif",',
    '    ".htm": "text/html; charset=utf-8",',
    '    ".html": "text/html; charset=utf-8",',
    '    ".ico": "image/x-icon",',
    '    ".jpeg": "image/jpeg",',
    '    ".jpg": "image/jpeg",',
    '    ".js": "text/javascript; charset=utf-8",',
    '    ".json": "application/json; charset=utf-8",',
    '    ".mjs": "text/javascript; charset=utf-8",',
    '    ".png": "image/png",',
    '    ".svg": "image/svg+xml",',
    '    ".txt": "text/plain; charset=utf-8",',
    '    ".webp": "image/webp",',
    '    ".woff": "font/woff",',
    '    ".woff2": "font/woff2",',
    '    ".xml": "application/xml; charset=utf-8",',
    "};",
    "",
    "function getExtension(pathname) {",
    '    const lastSlashIndex = pathname.lastIndexOf("/");',
    '    const lastDotIndex = pathname.lastIndexOf(".");',
    "",
    "    if (lastDotIndex <= lastSlashIndex) {",
    '        return "";',
    "    }",
    "",
    "    return pathname.slice(lastDotIndex).toLowerCase();",
    "}",
    "",
    "function getContentType(pathname) {",
    "    return (",
    "        contentTypeByExtension[getExtension(pathname)] ??",
    '        "application/octet-stream"',
    "    );",
    "}",
    "",
    "function getFirstHeaderValue(value) {",
    '    return value?.split(",")[0]?.trim() ?? "";',
    "}",
    "",
    "function getRuntimeEnv(name) {",
    "    if (globalThis.Deno?.env?.get) {",
    "        const value = globalThis.Deno.env.get(name);",
    "",
    "        if (value !== undefined) {",
    "            return value;",
    "        }",
    "    }",
    "",
    "    return globalThis.process?.env?.[name];",
    "}",
    "",
    "function getConfiguredOrigin() {",
    "    const rawOrigin =",
    '        getRuntimeEnv("APP_ORIGIN") ||',
    '        getRuntimeEnv("PUBLIC_APP_ORIGIN") ||',
    '        getRuntimeEnv("ASTRO_SITE");',
    "",
    "    if (!rawOrigin?.trim()) {",
    '        return "";',
    "    }",
    "",
    "    try {",
    "        return new URL(rawOrigin.trim()).origin;",
    "    } catch {",
    "        console.warn(`[server] Ignoring invalid APP_ORIGIN/PUBLIC_APP_ORIGIN/ASTRO_SITE value: ${rawOrigin}`);",
    '        return "";',
    "    }",
    "}",
    "",
    "function getForwardedOrigin(request) {",
    '    const proto = getFirstHeaderValue(request.headers.get("x-forwarded-proto"));',
    '    const host = getFirstHeaderValue(request.headers.get("x-forwarded-host"));',
    "",
    "    if (!proto || !host) {",
    '        return "";',
    "    }",
    "",
    "    return `${proto}://${host}`;",
    "}",
    "",
    "function createPublicRequest(request) {",
    "    if (isDenoWebSocketUpgradeRequest(request)) {",
    "        return request;",
    "    }",
    "",
    "    const publicOrigin = getConfiguredOrigin() || getForwardedOrigin(request);",
    "",
    "    if (!publicOrigin) {",
    "        return request;",
    "    }",
    "",
    "    const currentUrl = new URL(request.url);",
    "    const publicUrl = new URL(currentUrl.href);",
    "    const originUrl = new URL(publicOrigin);",
    "",
    "    publicUrl.protocol = originUrl.protocol;",
    "    publicUrl.host = originUrl.host;",
    "",
    "    if (publicUrl.href === currentUrl.href) {",
    "        return request;",
    "    }",
    "",
    "    return new Request(publicUrl, request);",
    "}",
    "",
    "function getSafeStaticFilePath(pathname) {",
    '    const normalizedPathname = pathname.startsWith("/") ? pathname : `/${pathname}`;',
    "    const targetUrl = new URL(`.${normalizedPathname}`, clientRootUrl);",
    "",
    "    if (!targetUrl.href.startsWith(clientRootUrl.href)) {",
    "        return null;",
    "    }",
    "",
    "    return targetUrl;",
    "}",
    "",
    "async function tryServeStaticFile(pathname) {",
    "    const candidateUrls = new Set();",
    "    const safeBaseUrl = getSafeStaticFilePath(pathname);",
    "",
    "    if (!safeBaseUrl) {",
    "        return null;",
    "    }",
    "",
    "    candidateUrls.add(safeBaseUrl.href);",
    "",
    '    if (!pathname.endsWith("/")) {',
    "        const indexUrl = getSafeStaticFilePath(`${pathname}/index.html`);",
    "",
    "        if (indexUrl) {",
    "            candidateUrls.add(indexUrl.href);",
    "        }",
    "    } else {",
    "        const indexUrl = getSafeStaticFilePath(`${pathname}index.html`);",
    "",
    "        if (indexUrl) {",
    "            candidateUrls.add(indexUrl.href);",
    "        }",
    "    }",
    "",
    "    for (const candidateUrl of candidateUrls) {",
    "        try {",
    "            const fileUrl = new URL(candidateUrl);",
    "            const fileInfo = await Deno.stat(fileUrl);",
    "",
    "            if (!fileInfo.isFile) {",
    "                continue;",
    "            }",
    "",
    "            const file = await Deno.readFile(fileUrl);",
    "",
    "            return new Response(file, {",
    "                headers: {",
    '                    "content-type": getContentType(fileUrl.pathname),',
    "                },",
    "            });",
    "        } catch (error) {",
    "            if (!(error instanceof Deno.errors.NotFound)) {",
    "                throw error;",
    "            }",
    "        }",
    "    }",
    "",
    "    return null;",
    "}",
    "",
    "const server = {",
    "    async fetch(request) {",
    "        const publicRequest = createPublicRequest(request);",
    "        const url = new URL(publicRequest.url);",
    "",
    "        const staticResponse = await tryServeStaticFile(url.pathname);",
    "",
    "        if (staticResponse) {",
    "            return staticResponse;",
    "        }",
    "",
    "        return handle(publicRequest, createDenoAstroRenderOptions(publicRequest));",
    "    },",
    "};",
    "",
    "export default server;",
    "",
].join("\n");
