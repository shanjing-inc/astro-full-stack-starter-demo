import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const rootDir = process.cwd();
const jobsDir = path.join(rootDir, "src/queues/jobs");
const manifestPath = path.join(jobsDir, "manifest.generated.ts");

function toImportIdentifier(fileName) {
    return fileName
        .replace(/\.job\.ts$/u, "")
        .replace(/[^a-zA-Z0-9]+(.)/gu, (_, char) => char.toUpperCase())
        .replace(/^[A-Z]/u, (char) => char.toLowerCase())
        .concat("JobModule");
}

const dirEntries = await readdir(jobsDir, {
    withFileTypes: true,
});

const jobFiles = dirEntries
    .filter((entry) => entry.isFile() && entry.name.endsWith(".job.ts"))
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right, "en"));

const imports = jobFiles
    .map((fileName) => {
        const identifier = toImportIdentifier(fileName);

        return `import * as ${identifier} from "./${fileName}";`;
    })
    .join("\n");

const moduleIdentifiers = jobFiles.map((fileName) => toImportIdentifier(fileName));
const moduleList =
    moduleIdentifiers.length > 0
        ? `[\n${moduleIdentifiers.map((identifier) => `    ${identifier},`).join("\n")}\n]`
        : "[]";

const source = `/**
 * This file is auto-generated by scripts/generate-queue-manifest.mjs.
 * Do not edit this file manually.
 */

import type { JobRegistry } from "@shanjing/astro-full-stack-starter/queue/core";
import { BaseQueueJob } from "@shanjing/astro-full-stack-starter/queue/core";
${imports ? `\n${imports}\n` : ""}
type QueueJobConstructor = new () => BaseQueueJob<unknown>;

export interface QueueJobModule {
    registerJob?: (registry: JobRegistry) => void;
    [key: string]: unknown;
}

export const queueJobModules: QueueJobModule[] = ${moduleList};

export function registerAllJobs(registry: JobRegistry) {
    for (const jobModule of queueJobModules) {
        let hasQueueJobClass = false;

        for (const exportedValue of Object.values(jobModule)) {
            if (typeof exportedValue !== "function") {
                continue;
            }

            if (!(exportedValue.prototype instanceof BaseQueueJob)) {
                continue;
            }

            const queueJob = new (exportedValue as QueueJobConstructor)();
            queueJob.register(registry);
            hasQueueJobClass = true;
        }

        if (!hasQueueJobClass) {
            jobModule.registerJob?.(registry);
        }
    }
}
`;

await writeFile(manifestPath, source);
console.log(
    `[queue:sync] Generated ${path.relative(rootDir, manifestPath)} with ${jobFiles.length} job modules.`
);
